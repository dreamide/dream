import {
  ArrowUp,
  Code,
  GitCommitHorizontal,
  GitPullRequest,
} from "lucide-react";
import { useTranslations } from "next-intl";
import {
  type FormEvent,
  useCallback,
  useEffect,
  useMemo,
  useState,
} from "react";
import { Button } from "@/components/ui/button";
import { Dialog, DialogContent } from "@/components/ui/dialog";
import { Input } from "@/components/ui/input";
import { Spinner } from "@/components/ui/spinner";
import { Switch } from "@/components/ui/switch";
import { Textarea } from "@/components/ui/textarea";
import { getApiErrorMessage } from "@/lib/api-client";
import type {
  AiProvider,
  ModelSpeed,
  ProjectGitCreatePrNextStep,
  ProjectGitStatusResponse,
  ReasoningEffort,
} from "@/types/ide";
import { getProjectHostId } from "../../../../electron/shared/persisted-state-codec.js";
import {
  cachedPullRequestDetails,
  generatePullRequestDetails,
} from "../git-generated-text";
import { useIdeStore } from "../ide-store";
import type { CreatePullRequestAction } from "./branch-actions";
import {
  ActionError,
  DialogMetricRow,
  GitDialogHeader,
  NextStepSelector,
} from "./dialog-layout";
import { GitDeltaSummary } from "./summary";

export const CreatePrDialog = ({
  action,
  branch,
  onCompleted,
  onOpenChange,
  open,
  model,
  modelSpeed,
  projectId,
  projectPath,
  provider,
  reasoningEffort,
  refreshToken,
  status,
}: {
  /** The branch actions' answer for creating a pull request from `branch`. */
  action: CreatePullRequestAction;
  branch: string | null;
  onCompleted: (url: string | null, openPrPage: boolean) => void;
  onOpenChange: (open: boolean) => void;
  open: boolean;
  model: string;
  modelSpeed: ModelSpeed;
  /** The project the pull request is created from (its git writes). */
  projectId: string;
  projectPath: string;
  provider: AiProvider;
  reasoningEffort: ReasoningEffort | null;
  refreshToken: number;
  status: ProjectGitStatusResponse | null;
}) => {
  const commonT = useTranslations("common");
  const gitT = useTranslations("git");
  const uiT = useTranslations("ui");
  const hostId = useIdeStore((state) =>
    getProjectHostId(
      [...state.projects, ...state.closedProjects].find(
        (project) => project.id === projectId,
      ),
    ),
  );
  const [title, setTitle] = useState("");
  const [description, setDescription] = useState("");
  const [autoGenerateDetails, setAutoGenerateDetails] = useState(true);
  const [generatedCommitMessage, setGeneratedCommitMessage] = useState<
    string | null
  >(null);
  const [generatingDetails, setGeneratingDetails] = useState(false);
  const [draft, setDraft] = useState(false);
  const [nextStep, setNextStep] =
    useState<ProjectGitCreatePrNextStep>("create");
  const [submitting, setSubmitting] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const { baseBranch, nextStep: defaultNextStep, nextSteps } = action;
  const branchError =
    action.problem === "detached-head"
      ? gitT("detachedHeadPrError")
      : action.problem === "same-branch"
        ? gitT("sameBranchPrError", { base: baseBranch, head: branch ?? "" })
        : null;
  const pullRequestChanges = useMemo(() => status?.changes ?? [], [status]);
  const hasDetails = Boolean(title.trim()) && Boolean(description.trim());
  const canCreate = !branchError && !generatingDetails && hasDetails;

  useEffect(() => {
    if (!open) {
      return;
    }

    setTitle("");
    setDescription("");
    setAutoGenerateDetails(true);
    setGeneratedCommitMessage(null);
    setGeneratingDetails(false);
    setDraft(false);
    setNextStep(defaultNextStep);
    setError(null);
  }, [defaultNextStep, open]);

  useEffect(() => {
    if (!(open && autoGenerateDetails) || branchError) {
      setGeneratingDetails(false);
      return;
    }

    const params = {
      baseBranch,
      branch,
      changes: pullRequestChanges,
      includeUnstaged: true,
      hostId,
      model,
      modelSpeed,
      nextStep,
      projectPath,
      provider,
      reasoningEffort,
      version: refreshToken,
    };
    const cachedDetails = cachedPullRequestDetails(params);
    if (cachedDetails !== undefined) {
      setTitle(cachedDetails.title);
      setDescription(cachedDetails.description);
      setGeneratedCommitMessage(cachedDetails.commitMessage);
      setGeneratingDetails(false);
      return;
    }

    let ignore = false;
    setTitle("");
    setDescription("");
    setGeneratedCommitMessage(null);
    setGeneratingDetails(true);
    void generatePullRequestDetails(params)
      .then((details) => {
        if (ignore) {
          return;
        }
        setTitle(details.title);
        setDescription(details.description);
        setGeneratedCommitMessage(details.commitMessage);
      })
      .catch((generationError: unknown) => {
        // The fields stay for the user to fill in; say why they are empty.
        if (!ignore) {
          setError(getApiErrorMessage(generationError, uiT("requestFailed")));
        }
      })
      .finally(() => {
        if (!ignore) {
          setGeneratingDetails(false);
        }
      });

    return () => {
      ignore = true;
    };
  }, [
    autoGenerateDetails,
    baseBranch,
    branch,
    branchError,
    hostId,
    nextStep,
    model,
    modelSpeed,
    open,
    projectPath,
    provider,
    pullRequestChanges,
    reasoningEffort,
    refreshToken,
    uiT,
  ]);

  const handleAutoGenerateDetailsChange = useCallback(
    (nextChecked: boolean) => {
      setAutoGenerateDetails(nextChecked);
      setGeneratingDetails(false);
      setError(null);
      if (!nextChecked) {
        setTitle("");
        setDescription("");
        setGeneratedCommitMessage(null);
      }
    },
    [],
  );

  const handleSubmit = useCallback(
    async (event: FormEvent<HTMLFormElement>) => {
      event.preventDefault();
      if (submitting || !canCreate) {
        return;
      }
      if (branchError) {
        setError(branchError);
        return;
      }

      setSubmitting(true);
      setError(null);
      const outcome = await useIdeStore
        .getState()
        .createProjectPullRequest(projectId, {
          baseBranch,
          commitMessage:
            nextStep === "commit-push-create" ? generatedCommitMessage : null,
          description,
          draft,
          includeUnstaged: true,
          nextStep,
          openPrPage: false,
          title,
        });
      setSubmitting(false);
      if (outcome.ok) {
        onCompleted(outcome.result.url, false);
        onOpenChange(false);
      } else {
        setError(getApiErrorMessage(outcome.error, gitT("unableToCreatePr")));
      }
    },
    [
      baseBranch,
      branchError,
      canCreate,
      description,
      draft,
      generatedCommitMessage,
      gitT,
      nextStep,
      onCompleted,
      onOpenChange,
      projectId,
      submitting,
      title,
    ],
  );

  return (
    <Dialog onOpenChange={onOpenChange} open={open}>
      <DialogContent className="max-h-[min(760px,calc(100vh-2rem))] grid-rows-[auto_minmax(0,1fr)] gap-5 overflow-hidden sm:max-w-2xl">
        <GitDialogHeader
          icon={<GitPullRequest />}
          subtitle={
            <>
              {branch ?? gitT("currentBranch")} -&gt; {baseBranch}
            </>
          }
          title={gitT("createPr")}
        />

        <form
          className="min-h-0 space-y-5 overflow-y-auto pr-1"
          onSubmit={handleSubmit}
        >
          <DialogMetricRow
            icon={<Code className="size-4" />}
            label={commonT("changes")}
            value={<GitDeltaSummary status={status} />}
          />

          <label
            className="flex items-center gap-3 text-sm"
            htmlFor="pr-auto-generate-details"
          >
            <Switch
              checked={autoGenerateDetails}
              id="pr-auto-generate-details"
              onCheckedChange={handleAutoGenerateDetailsChange}
            />
            <span>{gitT("autoGeneratePrDetails")}</span>
          </label>

          <div className="space-y-2">
            <label className="font-medium text-sm" htmlFor="pr-title">
              {commonT("title")}
            </label>
            <div className="relative">
              <Input
                aria-busy={generatingDetails}
                id="pr-title"
                onChange={(event) => setTitle(event.target.value)}
                placeholder={generatingDetails ? "" : gitT("enterTitle")}
                readOnly={autoGenerateDetails}
                value={title}
              />
              {generatingDetails ? (
                <div className="pointer-events-none absolute inset-0 flex items-center gap-2 px-3 text-muted-foreground text-sm">
                  <Spinner className="size-4" />
                  <span>{gitT("generatingTitle")}</span>
                </div>
              ) : null}
            </div>
          </div>

          <div className="space-y-2">
            <label className="font-medium text-sm" htmlFor="pr-description">
              {commonT("description")}
            </label>
            <div className="relative">
              <Textarea
                aria-busy={generatingDetails}
                className="h-32 max-h-32 min-h-32 resize-none overflow-y-auto"
                id="pr-description"
                onChange={(event) => setDescription(event.target.value)}
                placeholder={generatingDetails ? "" : gitT("enterDescription")}
                readOnly={autoGenerateDetails}
                value={description}
              />
              {generatingDetails ? (
                <div className="pointer-events-none absolute inset-0 flex items-center justify-center gap-2 text-muted-foreground text-sm">
                  <Spinner className="size-4" />
                  <span>{gitT("generatingDescription")}</span>
                </div>
              ) : null}
            </div>
          </div>

          <div className="space-y-2">
            <div className="font-medium text-sm">{gitT("nextSteps")}</div>
            <NextStepSelector<ProjectGitCreatePrNextStep>
              idPrefix="pr-next-step"
              onValueChange={setNextStep}
              options={[
                {
                  disabled: !nextSteps.includes("create"),
                  icon: <GitPullRequest />,
                  label: gitT("createPr"),
                  value: "create",
                },
                {
                  disabled: !nextSteps.includes("push-create"),
                  icon: <ArrowUp />,
                  label: gitT("pushAndCreatePr"),
                  value: "push-create",
                },
                {
                  disabled: !nextSteps.includes("commit-push-create"),
                  icon: <GitCommitHorizontal />,
                  label: gitT("commitPushAndCreatePr"),
                  value: "commit-push-create",
                },
              ]}
              value={nextStep}
            />
          </div>

          <ActionError error={error ?? branchError} />

          <div className="flex flex-wrap items-center gap-4">
            <label
              className="flex items-center gap-2 text-sm"
              htmlFor="pr-draft"
            >
              <Switch
                checked={draft}
                id="pr-draft"
                onCheckedChange={setDraft}
              />
              <span>{gitT("draft")}</span>
            </label>
            <Button
              className="ml-auto min-w-36"
              disabled={submitting || !canCreate}
              type="submit"
            >
              {submitting ? <Spinner className="size-4" /> : null}
              <span>{gitT("createPr")}</span>
            </Button>
          </div>
        </form>
      </DialogContent>
    </Dialog>
  );
};
